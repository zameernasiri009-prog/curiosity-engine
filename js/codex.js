export class CodexManager {
  constructor(backendStore) {
    this.backend = backendStore;
    this.modalEl = document.getElementById("overlay-codex");
    this.listEl = document.getElementById("codex-list");
    this.summaryEl = document.getElementById("codex-summary");
    this.bindUI();
  }

  bindUI() {
    const openBtn = document.getElementById("btn-open-codex");
    const closeBtn = document.getElementById("btn-close-codex");

    if (openBtn) {
      openBtn.addEventListener("click", () => this.open());
    }
    if (closeBtn) {
      closeBtn.addEventListener("click", () => this.close());
    }
  }

  getEntries() {
    const unlockedSet = new Set(this.backend.profile.discoveredCodes || []);
    return Object.entries(CODEX_CATALOG).map(([id, item]) => ({
      id,
      ...item,
      unlocked: unlockedSet.has(id)
    }));
  }

  open() {
    this.render();
    if (this.modalEl) {
      this.modalEl.classList.add("active");
    }
  }

  close() {
    if (this.modalEl) {
      this.modalEl.classList.remove("active");
    }
  }

  render() {
    if (!this.listEl || !this.summaryEl) return;
    const entries = this.getEntries();
    const unlockedCount = entries.filter((e) => e.unlocked).length;

    this.summaryEl.textContent = `Unlocked ${unlockedCount} / ${entries.length} Anomaly Dossiers`;
    this.listEl.innerHTML = "";

    for (const entry of entries) {
      const card = document.createElement("article");
      card.className = `codex-item ${entry.unlocked ? "unlocked" : "locked"}`;

      const header = document.createElement("div");
      header.className = "codex-item-head";
      header.textContent = entry.unlocked
        ? `${entry.code} // ${entry.title}`
        : `${entry.code} // UNDISCOVERED SIGNAL`;

      const meta = document.createElement("div");
      meta.className = "codex-item-meta";
      meta.textContent = `${entry.chamber} • ${entry.classification}`;

      const body = document.createElement("p");
      body.className = "codex-item-body";
      body.textContent = entry.unlocked
        ? `${entry.observation} "${entry.curiosityNote}"`
        : "Probe this anomaly during an active chamber run to decrypt its telemetry and curiosity note.";

      card.appendChild(header);
      card.appendChild(meta);
      card.appendChild(body);
      this.listEl.appendChild(card);
    }
  }
}
